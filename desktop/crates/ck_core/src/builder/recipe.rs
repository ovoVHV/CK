use serde::{Deserialize, Serialize};
use std::path::PathBuf;

#[derive(Serialize, Deserialize, Debug, Clone)]
pub struct BuildRecipe {
    pub fqbn: String,
    // The Compiler executable (e.g. /path/to/g++)
    pub compiler_path: PathBuf,
    // Arguments for compiling the sketch (generic args like -c -g -Os -w -std=gnu++17 ...)
    pub compiler_args: Vec<String>,
    // The expected output path for the sketch object file by arduino-cli (we might need to adjust this)
    pub sketch_obj_path: PathBuf,

    // The Linker executable (e.g. /path/to/ld or g++)
    pub linker_path: PathBuf,
    // Arguments for linking (including -o, -L, -l, object files, etc.)
    pub linker_args: Vec<String>,

    // The objcopy/esptool command to create the binary
    pub objcopy_cmd: Vec<String>,

    // Path to the preprocessed sketch .cpp file generated by arduino-cli
    // We will overwrite this file with our own wrapper wrapped around user code.
    pub sketch_cpp_path: PathBuf,
}

impl BuildRecipe {
    pub fn save(&self, path: &std::path::Path) -> anyhow::Result<()> {
        let json = serde_json::to_string_pretty(self)?;
        std::fs::write(path, json)?;
        Ok(())
    }

    pub fn load(path: &std::path::Path) -> anyhow::Result<Self> {
        let content = std::fs::read_to_string(path)?;
        let recipe = serde_json::from_str(&content)?;
        Ok(recipe)
    }
}

// RESTORED STRUCTS for legacy resolver support
#[derive(Debug, Clone)]
pub struct CompileRecipe {
    pub object_file: PathBuf,
    pub source_file: PathBuf,
    pub command_line: Vec<String>,
}

#[derive(Debug, Clone)]
pub struct LinkRecipe {
    pub output_file: PathBuf,
    pub object_files: Vec<PathBuf>,
    pub command_line: Vec<String>,
}
